import test from "node:test";
import assert from "node:assert/strict";
import { verifyP256Signature } from "../src/security.js";

const { canonicalJson, encryptSave, decryptSave, signSaveRequest } = await import("../../neon-shard/js/account/cloud-crypto.js");

test("browser ECDH + HKDF + AES-GCM envelope round-trips and detects tampering", async () => {
  const pair = await crypto.subtle.generateKey(
    { name: "ECDH", namedCurve: "P-256" },
    true,
    ["deriveBits"],
  );
  const keys = {
    encryptionPrivateKey: pair.privateKey,
    encryptionPublicKey: await crypto.subtle.exportKey("jwk", pair.publicKey),
    keyId: "test-key-1",
  };
  const userId = "d6f9b42d-22d2-4ef2-8e8f-c07c6e0b1f00";
  const save = { coins: 42, own: [0, 1, 3], nested: { cleared: true } };
  const envelope = await encryptSave(userId, keys, save);
  assert.deepEqual(await decryptSave(userId, keys, envelope), save);

  const altered = { ...envelope, ephemeralPublicKey: { ...envelope.ephemeralPublicKey, x: "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA" } };
  await assert.rejects(() => decryptSave(userId, keys, altered));
});

test("browser ECDSA signature matches server IEEE-P1363 verification", async () => {
  const pair = await crypto.subtle.generateKey(
    { name: "ECDSA", namedCurve: "P-256" },
    true,
    ["sign", "verify"],
  );
  const signingPublicKey = await crypto.subtle.exportKey("jwk", pair.publicKey);
  const keys = { signingPrivateKey: pair.privateKey, keyId: "test-key-1" };
  const body = {
    saveData: { format: "neon-shard-save-v1" },
    sensitiveEnvelope: {
      cryptoVersion: 1,
      keyId: "test-key-1",
      schemaVersion: 1,
      ephemeralPublicKey: { kty: "EC", crv: "P-256", x: "eA", y: "eQ" },
      iv: "AAAAAAAAAAAAAAAA",
      ciphertext: "Y2lwaGVy",
      tag: "AAAAAAAAAAAAAAAAAAAAAA",
    },
    keyId: "test-key-1",
    signedAt: Date.now(),
    expectedRevision: 2,
  };
  const signature = await signSaveRequest(keys, {
    userId: "user-1",
    method: "PUT",
    path: "/api/player-data",
    body,
  });
  const message = canonicalJson({
    purpose: "neon-shard:save-request:v1",
    userId: "user-1",
    method: "PUT",
    path: "/api/player-data",
    signedAt: body.signedAt,
    keyId: body.keyId,
    expectedRevision: body.expectedRevision,
    saveData: body.saveData,
    sensitiveEnvelope: body.sensitiveEnvelope,
  });
  // Verify against the exact canonical JSON generated by the browser module.
  assert.equal(verifyP256Signature(signingPublicKey, message, signature), true);
  assert.equal(verifyP256Signature(signingPublicKey, message + " ", signature), false);
});
